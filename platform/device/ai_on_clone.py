#!/usr/bin/env python3
"""
Run the neural network's forward pass on the CPU clone and verify it.

The forward pass is emitted as x86-64 machine code by ai_model.emit_asm, then
executed by device/cpu.py — the independently implemented engine. Every
multiply and add of the network is decoded and executed by the clone.

numpy is used only as a reference to prove the clone's integer arithmetic is
identical. It performs no part of the inference that is being measured.

Verification has two levels:
  1. per-token: the clone's predicted index must equal the numpy integer
     reference for every context in the corpus.
  2. end-to-end: the text generated by the clone must match the text generated
     by the numpy reference, character for character.
"""

import os
import subprocess
import sys
import tempfile

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ai_model import train, quantize, emit_asm, data_bytes, layout, ref_forward  # noqa: E402
from cpu import CPU  # noqa: E402

WEIGHTS_BASE = 0x600000


def assemble(asm):
    """Assemble the emitted assembly to machine code bytes."""
    d = tempfile.mkdtemp()
    spath = os.path.join(d, "f.s")
    opath = os.path.join(d, "f.o")
    with open(spath, "w") as f:
        f.write(asm)
    subprocess.run(["gcc", "-c", "-o", opath, spath], check=True, capture_output=True)
    import re
    out = subprocess.run(["objdump", "-d", opath], check=True,
                         capture_output=True, text=True).stdout
    code = []
    for line in out.splitlines():
        m = re.match(r"^\s+[0-9a-f]+:\s+((?:[0-9a-f]{2} )+)", line)
        if m:
            code.extend(m.group(1).split())
    return bytes(int(b, 16) for b in code)


class CloneNet:
    """The neural network, executed entirely by the CPU clone."""

    def __init__(self, q, code):
        self.q = q
        self.code = code
        self.cpu = CPU()
        # lay the weights out in memory, then load the program above them
        base = self.cpu.load(data_bytes(q), WEIGHTS_BASE)
        self.code_addr = self.cpu.load(code, 0x400000)
        self.fwd_addr = self.code_addr

    def predict(self, ctx):
        """Run one forward pass on the clone; return the predicted index."""
        c = self.cpu
        c.reg[0] = 0
        c.reg[3] = 0
        c.reg[1] = 0
        c.reg[2] = 0
        c.halted = False
        return c.call(self.fwd_addr, *ctx)


def main():
    print("Training the model (float, numpy, for weights only)…")
    model = train()
    q = quantize(model)
    print(f"  vocab={q['V']} hidden={q['H']} context={q['K']} "
          f"float accuracy={model['float_acc']:.3f}")

    asm = emit_asm(q, WEIGHTS_BASE)
    code = assemble(asm)
    print(f"  forward pass assembled to {len(code)} bytes of x86-64 "
          f"({asm.count(chr(10))} assembly lines)")

    net = CloneNet(q, code)

    # 1. per-token verification
    vocab = q["vocab"]
    idx = {c: i for i, c in enumerate(vocab)}
    corpus = model.get("corpus", None)
    from ai_model import CORPUS
    data = [idx[c] for c in CORPUS]
    K = q["K"]
    mismatches = 0
    total = 0
    for i in range(K, len(data)):
        ctx = data[i - K:i]
        want = ref_forward(q, ctx)          # numpy integer reference
        got = net.predict(ctx)              # clone execution
        total += 1
        if got != want:
            mismatches += 1
            if mismatches == 1:
                print(f"  first mismatch: ctx={ctx} clone={got} ref={want}")
    print(f"\nper-token verification: {total} contexts, {mismatches} mismatches")
    ok = mismatches == 0

    # 2. end-to-end generation: clone vs numpy reference
    def generate(engine, prompt, n=60):
        out = [idx[c] for c in prompt]
        for _ in range(n):
            ctx = out[-K:]
            nxt = engine(ctx)
            out.append(nxt)
        return "".join(vocab[i] for i in out)

    prompt = "the "
    clone_text = generate(lambda ctx: net.predict(ctx), prompt)
    ref_text = generate(lambda ctx: ref_forward(q, ctx), prompt)
    same_text = clone_text == ref_text
    print(f"\ngeneration (clone):  {clone_text!r}")
    print(f"generation (ref):    {ref_text!r}")
    print(f"text identical: {same_text}")
    ok = ok and same_text

    # 3. timing: how fast can the clone run one forward pass?
    import time
    ctx = data[:K]
    reps = 2000
    before = net.cpu.insns
    t0 = time.perf_counter()
    for _ in range(reps):
        net.predict(ctx)
    dt = time.perf_counter() - t0
    per_pass = (net.cpu.insns - before) // reps
    print(f"\nclone inference speed: {reps/dt:,.0f} forward passes/s "
          f"({dt/reps*1e6:.1f} us each)")
    print(f"  instructions per forward pass: {per_pass:,} "
          f"(decoded and executed by device/cpu.py)")

    print("\n" + "=" * 64)
    print("CLONE-NET RESULT:", "ALL PASS — inference runs on the clone"
          if ok else "FAILURES PRESENT")
    print("=" * 64)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
